// Recetas de estilo de renders de internet: isla de terreno + estilo + render + plantilla + exportar.
// Uso: npx electron scripts/smoke-styles.cjs <carpeta-salida>
const { app, BrowserWindow, dialog, nativeImage } = require('electron')
const path = require('node:path')
const fs = require('node:fs')
const out = path.resolve(process.argv[process.argv.length - 1])
fs.mkdirSync(out, { recursive: true })
dialog.showSaveDialog = async (_w, o) => ({ canceled: false, filePath: path.join(out, path.basename(o.defaultPath)) })
require('../out/main/index.js')
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

app.whenReady().then(async () => {
  let win
  while (!(win = BrowserWindow.getAllWindows()[0])) await sleep(100)
  win.setSize(1600, 960)
  const errors = []
  win.webContents.on('console-message', (e) => { if (e.level === 'error') errors.push(e.message) })
  await new Promise((r) => win.webContents.once('did-finish-load', r))
  await sleep(4000)
  const js = (c) => win.webContents.executeJavaScript(c)
  const click = (text, sel = 'button') => js(`(() => { const b = [...document.querySelectorAll(${JSON.stringify(sel)})].find(x => x.textContent.trim().startsWith(${JSON.stringify(text)}) && !x.disabled); if (!b) return 'NO ' + ${JSON.stringify(text)}; b.click(); return 'ok' })()`)
  const setSelect = (label, value) => js(`(() => { const f = [...document.querySelectorAll('.panel.right .field')].find(x => x.querySelector('.lbl')?.textContent === ${JSON.stringify(label)}); const sel = f?.querySelector('select'); if (!sel) return 'NO ' + ${JSON.stringify(label)}; const set = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set; set.call(sel, ${JSON.stringify(value)}); sel.dispatchEvent(new Event('change', { bubbles: true })); return 'ok' })()`)
  const shot = async (n) => fs.writeFileSync(path.join(out, n + '.png'), (await win.webContents.capturePage()).toPNG())
  const closeAll = () => js(`document.querySelectorAll('.toast .icon-btn').forEach(b => b.click()); document.querySelector('.modal-head .icon-btn')?.click(); true`)
  await js('window.confirm = () => true; true')
  await click('Escena de ejemplo')
  await sleep(5000)

  async function recipe(tag, islandStyle, look, template) {
    await js(`window.dispatchEvent(new KeyboardEvent('keydown', { key: '1', ctrlKey: true })); true`)
    await sleep(300)
    console.log(tag, 'base', await click('Base de exhibición', '.tree-row.obj'))
    await click('Objeto', '.panel.right .seg button')
    await sleep(300)
    console.log(tag, 'forma', await setSelect('Forma', 'island'))
    await sleep(500)
    console.log(tag, 'terreno', await setSelect('Terreno', islandStyle))
    await sleep(800)
    // ocultar árboles, roca y farolas sueltos para una pieza aislada
    await js(`[...document.querySelectorAll('.tree-row.obj')].filter(r => /Árbol|Roca|Farola/.test(r.textContent)).forEach(r => { const b = r.querySelector('button[aria-label="Ocultar"]'); b?.click() }); true`)
    await click('Render', '.panel.right .seg button')
    console.log(tag, 'estilo', await click(look, '.panel.right .tpl-card'))
    await sleep(800)
    await js(`window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' })); true`)
    await click('¾')
    await sleep(1400)
    await closeAll()
    await shot(`${tag}-visor`)
    await js(`window.dispatchEvent(new KeyboardEvent('keydown', { key: 'F12' })); true`)
    await sleep(500)
    await js(`(() => { [...document.querySelectorAll('.modal .seg button')].find(b => b.textContent === '16')?.click(); const f = [...document.querySelectorAll('.modal .field')].find(x => x.textContent.startsWith('Fondo transparente')); f?.querySelector('input')?.click(); return true })()`)
    await click('Render final', '.modal-foot button')
    for (let i = 0; i < 160 && !(await js(`!!document.querySelector('.modal .callout.ok img')`)); i++) await sleep(500)
    await closeAll()
    await js(`window.dispatchEvent(new KeyboardEvent('keydown', { key: '2', ctrlKey: true })); true`)
    await sleep(600)
    console.log(tag, 'plantilla', await click(template, '.comp-left .tpl-card'))
    await sleep(1200)
    await js(`window.dispatchEvent(new KeyboardEvent('keydown', { key: 'e', ctrlKey: true })); true`)
    await sleep(400)
    await click('Generar vista previa', '.modal button')
    for (let i = 0; i < 60 && !(await js(`!!document.querySelector('.modal .preview-img')`)); i++) await sleep(300)
    await click('Guardar', '.modal-foot button')
    await sleep(1500)
    await closeAll()
  }
  await recipe('roma', 'seca', 'Colección pergamino', 'Colección con etiquetas')
  await recipe('pastel', 'verde', 'Paquete pastel', 'Paquete de construcciones')
  for (const f of fs.readdirSync(out).filter((x) => x.endsWith('.png') && !/visor/.test(x))) console.log('exportado:', f, JSON.stringify(nativeImage.createFromPath(path.join(out, f)).getSize()))
  console.log('errores consola:', errors.slice(0, 3))
  app.exit(0)
})
