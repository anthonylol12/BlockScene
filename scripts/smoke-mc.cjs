// Prueba visual con las texturas de la instalación local de Minecraft.
// Uso: npx electron scripts/smoke-mc.cjs <carpeta-salida>
const { app, BrowserWindow } = require('electron')
const path = require('node:path')
const fs = require('node:fs')
const out = path.resolve(process.argv[process.argv.length - 1])
fs.mkdirSync(out, { recursive: true })
require('../out/main/index.js')
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

app.whenReady().then(async () => {
  let win
  while (!(win = BrowserWindow.getAllWindows()[0])) await sleep(100)
  win.setSize(1600, 960)
  win.webContents.on('console-message', (e) => { if (e.level === 'error') console.log('[error]', e.message) })
  await new Promise((r) => win.webContents.once('did-finish-load', r))
  await sleep(1500)
  const js = (c) => win.webContents.executeJavaScript(c)
  const click = (text, sel = 'button') => js(`(() => { const b = [...document.querySelectorAll(${JSON.stringify(sel)})].find(x => x.textContent.trim().startsWith(${JSON.stringify(text)}) && !x.disabled); if (!b) return 'NO ' + ${JSON.stringify(text)}; b.click(); return 'ok' })()`)
  const shot = async (n) => { fs.writeFileSync(path.join(out, n + '.png'), (await win.webContents.capturePage()).toPNG()); console.log('captura', n) }
  console.log(await click('Escena de ejemplo'))
  await sleep(5000)
  console.log(await click('Render', '.panel.right .seg button'))
  await sleep(300)
  console.log(await click('Usar mi Minecraft', '.panel.right button'))
  await sleep(9000)
  console.log(await js(`document.querySelector('.panel.right .callout')?.innerText`))
  await js(`document.querySelectorAll('.toast .icon-btn').forEach(b => b.click()); true`)
  await shot('mc-01-demo')
  console.log(await click('¾'))
  await sleep(1500)
  await shot('mc-02-tres-cuartos')
  await js(`window.dispatchEvent(new KeyboardEvent('keydown', {key: 'Escape'})); true`)
  await sleep(300)
  await js(`(() => { const c = document.querySelector('.viewport canvas'); const r = c.getBoundingClientRect(); for (let i = 0; i < 14; i++) c.dispatchEvent(new WheelEvent('wheel', { deltaY: -120, clientX: r.left + r.width / 2, clientY: r.top + r.height / 2, bubbles: true })); return true })()`)
  await sleep(1500)
  await shot('mc-03-cerca')
  app.exit(0)
})
