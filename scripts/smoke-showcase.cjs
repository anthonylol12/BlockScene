// Flujo de exhibición: demo → estilo "Exhibición oscura" → render final → plantilla "Exhibición" → exportar PNG.
// Uso: npx electron scripts/smoke-showcase.cjs <carpeta-salida>
const { app, BrowserWindow, dialog, nativeImage } = require('electron')
const path = require('node:path')
const fs = require('node:fs')
const out = path.resolve(process.argv[process.argv.length - 1])
fs.mkdirSync(out, { recursive: true })
dialog.showSaveDialog = async (_w, o) => ({ canceled: false, filePath: path.join(out, path.basename(o.defaultPath)) })
require('../out/main/index.js')
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

app.whenReady().then(async () => {
  let win
  while (!(win = BrowserWindow.getAllWindows()[0])) await sleep(100)
  win.setSize(1600, 960)
  const errors = []
  win.webContents.on('console-message', (e) => { if (e.level === 'error') errors.push(e.message) })
  await new Promise((r) => win.webContents.once('did-finish-load', r))
  await sleep(4000) // carga de texturas guardadas
  const js = (c) => win.webContents.executeJavaScript(c)
  const click = (text, sel = 'button') => js(`(() => { const b = [...document.querySelectorAll(${JSON.stringify(sel)})].find(x => x.textContent.trim().startsWith(${JSON.stringify(text)}) && !x.disabled); if (!b) return 'NO ' + ${JSON.stringify(text)}; b.click(); return 'ok' })()`)
  const shot = async (n) => fs.writeFileSync(path.join(out, n + '.png'), (await win.webContents.capturePage()).toPNG())
  await js('window.confirm = () => true; true')
  console.log('demo', await click('Escena de ejemplo'))
  await sleep(6000)
  console.log('tab', await click('Render', '.panel.right .seg button'))
  console.log('estilo', await click('Exhibición oscura', '.panel.right .tpl-card'))
  await sleep(1500)
  await js(`document.querySelectorAll('.toast .icon-btn').forEach(b => b.click()); window.dispatchEvent(new KeyboardEvent('keydown', {key: 'Escape'})); true`)
  console.log('vista', await click('¾'))
  await sleep(1500)
  await shot('show-01-visor')
  await js(`window.dispatchEvent(new KeyboardEvent('keydown', {key: 'F12'})); true`)
  await sleep(500)
  await js(`(() => { const s = [...document.querySelectorAll('.modal .seg button')].find(b => b.textContent === '16'); s?.click(); return true })()`)
  console.log('render', await click('Render final', '.modal-foot button'))
  for (let i = 0; i < 120 && !(await js(`!!document.querySelector('.modal .callout.ok img')`)); i++) await sleep(500)
  await js(`document.querySelector('.modal-head .icon-btn')?.click(); true`)
  await js(`window.dispatchEvent(new KeyboardEvent('keydown', {key: '2', ctrlKey: true})); true`)
  await sleep(600)
  console.log('plantilla', await click('Exhibición', '.comp-left .tpl-card'))
  await sleep(1200)
  await shot('show-02-compositor')
  await js(`window.dispatchEvent(new KeyboardEvent('keydown', {key: 'e', ctrlKey: true})); true`)
  await sleep(400)
  await click('Generar vista previa', '.modal button')
  for (let i = 0; i < 60 && !(await js(`!!document.querySelector('.modal .preview-img')`)); i++) await sleep(300)
  await click('Guardar', '.modal-foot button')
  await sleep(1500)
  const f = fs.readdirSync(out).find((x) => x.startsWith('Exhibici') && x.endsWith('.png'))
  console.log('exportado:', f, f ? nativeImage.createFromPath(path.join(out, f)).getSize() : null)
  console.log('errores consola:', errors.length ? errors.slice(0, 3) : 'ninguno')
  app.exit(0)
})
